/// Safe lookup — 29-day Ramadans exist, and a stale local clock could put
/// `dayNumber` momentarily out of [1, 30]; falls back to day 1 rather than
/// throwing on a list index.
RamadanDuaOfDay ramadanDuaForDay(int day) {
  final clamped = day.clamp(1, ramadanDuasOfDay.length);
  return ramadanDuasOfDay[clamped - 1];
}
